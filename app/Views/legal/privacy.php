            <div class="legal-section">
                <h2>1. Information We Collect</h2>
                <p>Cabin is built on a strict <strong>zero-data-collection</strong> philosophy. We do <strong>not</strong> collect:</p>
                <ul>
                    <li>Your name, email address, or any personal identifiers</li>
                    <li>IP addresses or device fingerprints</li>
                    <li>Browser cookies or tracking pixels</li>
                    <li>Usage analytics or behavioral data</li>
                    <li>The content of your notes (notes are encrypted before storage)</li>
                </ul>
                <p>The only data stored is the encrypted ciphertext of your note, a randomly generated URL slug, and an expiry timestamp. None of this can be linked to your identity.</p>
            </div>

            <div class="legal-section">
                <h2>2. How Your Notes Are Stored</h2>
                <p>Every note created on Cabin is encrypted using <strong>AES-256</strong> — the same standard used by governments and financial institutions worldwide.</p>
                <ul>
                    <li><strong>Encryption at rest:</strong> Notes are stored in encrypted form in our database.</li>
                    <li><strong>No decryption logs:</strong> We do not log when or how many times a note is viewed.</li>
                    <li><strong>Auto-deletion:</strong> Notes are permanently and irreversibly deleted after their set expiry time or after they are viewed (if "Burn After Read" is enabled).</li>
                </ul>
            </div>

            <div class="legal-section">
                <h2>3. Cookies</h2>
                <p>Cabin uses <strong>no third-party cookies</strong> and no tracking scripts. A single, temporary session cookie may be used strictly for CSRF (Cross-Site Request Forgery) protection — a security measure. This cookie:</p>
                <ul>
                    <li>Contains no personal information</li>
                    <li>Is never shared with any third party</li>
                    <li>Expires when your browser session ends</li>
                </ul>
            </div>

            <div class="legal-section">
                <h2>4. Third-Party Services</h2>
                <p>Cabin does not integrate any third-party analytics, advertising, or social tracking tools (e.g. Google Analytics, Facebook Pixel, Hotjar). Our infrastructure runs on <strong>Vercel</strong> and <strong>TiDB Cloud</strong>. Their own privacy policies apply to infrastructure-level logging. We do not share any user data with these providers beyond what is technically necessary to serve the application.</p>
            </div>

            <div class="legal-section">
                <h2>5. Data Retention</h2>
                <p>Notes are deleted automatically based on the expiry window chosen at creation (5 minutes, 1 hour, 24 hours, 7 days, or 30 days). After deletion:</p>
                <ul>
                    <li>The encrypted content is permanently removed from our database.</li>
                    <li>The process is irreversible — we cannot recover deleted notes.</li>
                    <li>No backups of note content are maintained.</li>
                </ul>
            </div>

            <div class="legal-section">
                <h2>6. Children's Privacy</h2>
                <p>Cabin is not directed to children under the age of 13. We do not knowingly collect any information from children. If you believe a child has used the platform in violation of this policy, please contact us and we will take appropriate action.</p>
